package dashboard_grafana

import (
	"context"
	"fmt"
	"time"

	"github.com/hashicorp/go-azure-helpers/lang/pointer"
	"github.com/hashicorp/go-azure-sdk/resource-manager/dashboard/2025-08-01/managedgrafanas"
	"github.com/hashicorp/terraform-provider-azurerm/internal/sdk"
)

func (r Resource) Update() sdk.ResourceFunc {
	return sdk.ResourceFunc{
		Timeout: 30 * time.Minute,
		Func: func(ctx context.Context, metadata sdk.ResourceMetaData) error {
			client := metadata.Client.Dashboard.GrafanaResourceClient

			id, err := managedgrafanas.ParseGrafanaID(metadata.ResourceData.Id())
			if err != nil {
				return err
			}

			var model DashboardGrafanaModel
			if err := metadata.Decode(&model); err != nil {
				return fmt.Errorf("decoding: %+v", err)
			}

			resp, err := client.GrafanaGet(ctx, *id)
			if err != nil {
				return fmt.Errorf("retrieving %s: %+v", *id, err)
			}

			properties := resp.Model
			if properties == nil {
				return fmt.Errorf("retrieving %s: properties was nil", id)
			}

			if metadata.ResourceData.HasChange("api_key_enabled") {
				apiKey := managedgrafanas.ApiKeyDisabled
				if model.ApiKeyEnabled {
					apiKey = managedgrafanas.ApiKeyEnabled
				}

				properties.Properties.ApiKey = &apiKey
			}

			if metadata.ResourceData.HasChange("auto_generated_domain_name_label_scope") {
				properties.Properties.AutoGeneratedDomainNameLabelScope = &model.AutoGeneratedDomainNameLabelScope
			}

			if metadata.ResourceData.HasChange("csrf_always_check") {
				if properties.Properties.GrafanaConfigurations == nil {
					properties.Properties.GrafanaConfigurations = &managedgrafanas.GrafanaConfigurations{}
				}
				properties.Properties.GrafanaConfigurations.Security = pointer.To(managedgrafanas.Security{
					CsrfAlwaysCheck: pointer.To(model.CsrfAlwaysCheck),
				})
			}

			if metadata.ResourceData.HasChange("deterministic_outbound_ip_enabled") {
				deterministicOutboundIP := managedgrafanas.DeterministicOutboundIPDisabled
				if model.DeterministicOutboundIPEnabled {
					deterministicOutboundIP = managedgrafanas.DeterministicOutboundIPEnabled
				}

				properties.Properties.DeterministicOutboundIP = &deterministicOutboundIP
			}

			if metadata.ResourceData.HasChange("azure_monitor_workspace_integrations") {
				properties.Properties.GrafanaIntegrations = expandGrafanaIntegrationsModel(model.AzureMonitorWorkspaceIntegrations)
			}

			if metadata.ResourceData.HasChange("public_network_access_enabled") {
				publicNetworkAccess := managedgrafanas.PublicNetworkAccessDisabled
				if model.PublicNetworkAccessEnabled {
					publicNetworkAccess = managedgrafanas.PublicNetworkAccessEnabled
				}

				properties.Properties.PublicNetworkAccess = &publicNetworkAccess
			}

			if metadata.ResourceData.HasChange("tags") {
				properties.Tags = &model.Tags
			}

			if metadata.ResourceData.HasChange("snapshot_external_enabled") {
				if properties.Properties.GrafanaConfigurations == nil {
					properties.Properties.GrafanaConfigurations = &managedgrafanas.GrafanaConfigurations{}
				}
				properties.Properties.GrafanaConfigurations.Snapshots = pointer.To(managedgrafanas.Snapshots{
					ExternalEnabled: pointer.To(model.SnapshotExternalEnabled),
				})
			}

			if metadata.ResourceData.HasChange("unified_alerting_screenshots_capture_enabled") {
				if properties.Properties.GrafanaConfigurations == nil {
					properties.Properties.GrafanaConfigurations = &managedgrafanas.GrafanaConfigurations{}
				}
				properties.Properties.GrafanaConfigurations.UnifiedAlertingScreenshots = pointer.To(managedgrafanas.UnifiedAlertingScreenshots{
					CaptureEnabled: pointer.To(model.UnifiedAlertingScreenshotsCaptureEnabled),
				})
			}

			if metadata.ResourceData.HasChange("users") {
				if properties.Properties.GrafanaConfigurations == nil {
					properties.Properties.GrafanaConfigurations = &managedgrafanas.GrafanaConfigurations{}
				}
				if len(model.UsersConfiguration) > 0 {
					v := model.UsersConfiguration[0]
					properties.Properties.GrafanaConfigurations.Users = pointer.To(managedgrafanas.Users{
						EditorsCanAdmin: pointer.To(v.EditorsCanAdmin),
						ViewersCanEdit:  pointer.To(v.ViewersCanEdit),
					})
				} else {
					properties.Properties.GrafanaConfigurations.Users = nil
				}
			}

			// The SMTP password is never returned by the API, so it must be re-expanded from config on every update,
			// not just when `smtp` changes, otherwise Azure rejects the request with `InvalidConfigurationForSMTP`.
			if properties.Properties.GrafanaConfigurations != nil {
				properties.Properties.GrafanaConfigurations.Smtp = expandSMTPConfigurationModel(model.SMTP)
			} else {
				properties.Properties.GrafanaConfigurations = expandGrafanaConfigurationsModel(model.SMTP, model.CsrfAlwaysCheck, model.SnapshotExternalEnabled, model.UnifiedAlertingScreenshotsCaptureEnabled, model.UsersConfiguration)
			}

			if metadata.ResourceData.HasChange("grafana_major_version") {
				properties.Properties.GrafanaMajorVersion = &model.GrafanaMajorVersion
			}

			if err := client.GrafanaCreateThenPoll(ctx, *id, *properties); err != nil {
				return fmt.Errorf("updating %s: %+v", *id, err)
			}

			return nil
		},
	}
}
